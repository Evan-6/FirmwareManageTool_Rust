#!/usr/bin/env python3
"""Generate portable key tables and minimal clients, or verify them all.

Sources of truth:
  shared/input-protocol/keys.json      physical key catalog
  shared/input-protocol/vectors.json   golden wire packets
  shared/input-protocol/src/v3.rs      opcode numbers (parsed, never duplicated)
  scripts/clients/*.in                 minimal Rust / C++ / Python clients
"""
from pathlib import Path
import argparse, json, re, shutil, subprocess
parser=argparse.ArgumentParser()
parser.add_argument('--check',action='store_true')
parser.add_argument('--peer',type=Path)
parser.add_argument('--mscv-rust',type=Path)
parser.add_argument('--mscv-cpp',type=Path)
a=parser.parse_args()
root=Path(__file__).resolve().parents[1]; shared=root/'shared/input-protocol'
s=json.loads((shared/'keys.json').read_text()); rows=s['keys']
def rustfmt_source(source):
    return subprocess.run(['rustfmt','--edition','2021'],input=source,text=True,capture_output=True,check=True).stdout
rust='// Generated by scripts/sync-input-protocol.py; edit keys.json.\n'
rust+='pub const KEYS: &[KeyEntry] = &[\n'
for r in rows:
    rust+=f'    KeyEntry {{ id: KeyId {{ usage_page: {r["page"]}, usage: {r["usage"]} }}, token: {json.dumps(r["token"])}, aliases: &'+json.dumps(r['aliases'])+', code: '+('Some('+json.dumps(r['code'])+')' if r['code'] else 'None')+' },\n'
rust+='];\n'
rust=rustfmt_source(rust)
js='// Generated from keys.json; physical KeyboardEvent.code identities.\nconst HID_KEY_CODE_MAP = '+json.dumps({r['code']:{'p':r['page'],'u':r['usage']} for r in rows if r['code']},indent=2)+';\n'
js+='const HID_KEY_TOKEN_MAP = '+json.dumps({t:{'p':r['page'],'u':r['usage']} for r in rows for t in [r['token']]+r['aliases']},indent=2)+';\n'
vectors=json.loads((shared/'vectors.json').read_text())
cpp_vectors='// Golden wire vectors from shared/input-protocol/vectors.json.\n#pragma once\nconstexpr uint8_t WireVectors[][64] = {\n'+''.join('{'+','.join(str(b) for b in v['bytes'])+'},\n' for v in vectors)+'};\n'
bitmap = [0] * 28
for r in rows:
    if r['page'] == 7 and r['usage'] < 224:
        bitmap[r['usage'] // 8] |= 1 << (r['usage'] % 8)
eng = ['// Generated from shared/input-protocol/keys.json; edit keys.json.']
eng.append('pub const CONSUMER_USAGES: [u16; 7] = [' + ', '.join(str(u) for u in s['consumer_usages']) + '];')
eng.append('/// Bit `u` is set when Keyboard usage `u` (< 224) is accepted.')
eng.append('pub const KEYBOARD_BITMAP: [u8; 28] = [' + ', '.join(str(b) for b in bitmap) + '];')
eng = rustfmt_source(chr(10).join(eng) + chr(10))
eng_vectors = ['// Generated from shared/input-protocol/vectors.json.']
eng_vectors.append('/// Full 64-byte HID reports exactly as the host codec emits them.')
eng_vectors.append('pub const WIRE_VECTORS: [[u8; 64]; ' + str(len(vectors)) + '] = [')
for v in vectors:
    eng_vectors.append('    [' + ', '.join(str(b) for b in v['bytes']) + '],')
eng_vectors.append('];')
eng_vectors = rustfmt_source(chr(10).join(eng_vectors) + chr(10))

# ---- opcodes: parsed from the shared Rust constants, then emitted per language.
WIRE = (shared/'src/v3.rs').read_text()
def opcode(name):
    found = re.search(r'pub const '+name+r': u8 = (\d+);', WIRE)
    if not found:
        raise SystemExit('opcode '+name+' missing from shared/input-protocol/src/v3.rs')
    return int(found.group(1))
# Clients use short stable names; the wire module keeps the longer ones.
NAMES = {
    'OPEN': 'OPEN', 'CLOSE': 'CLOSE', 'HEARTBEAT': 'HEARTBEAT', 'BARRIER': 'BARRIER',
    'RELEASE': 'RELEASE_ALL', 'STATUS': 'STATUS', 'STATUS_EXT': 'STATUS_EXT',
    'SESSION_LIST': 'SESSION_LIST', 'BOOTLOADER': 'BOOTLOADER', 'KEY': 'KEY',
    'SNAPSHOT': 'SNAPSHOT', 'MOVE': 'MOUSE_MOVE', 'BUTTONS': 'MOUSE_BUTTONS',
    'WHEEL': 'WHEEL', 'EVENT': 'EVENT',
}
ORDER = list(NAMES)
values = {name: opcode(wire) for name, wire in NAMES.items()}
blocks = {
    'python': ''.join(f'{name} = 0x{values[name]:02X}\n' for name in ORDER),
    'cpp': ''.join(f'constexpr std::uint8_t {name} = 0x{values[name]:02X};\n' for name in ORDER),
    'rust': ''.join(f'pub const {name}: u8 = 0x{values[name]:02X};\n' for name in ORDER),
}
headers = {
    'python': 'Generated by scripts/sync-input-protocol.py from shared/input-protocol/src/v3.rs; edit scripts/clients/hid_v3.py.in.',
    'cpp': 'Generated by scripts/sync-input-protocol.py from shared/input-protocol/src/v3.rs; edit scripts/clients/hid_v3.hpp.in.',
    'rust': 'Generated by scripts/sync-input-protocol.py from shared/input-protocol/src/v3.rs; edit scripts/clients/hid_v3.rs.in.',
}
templates = {'python': ('hid_v3.py.in', root/'clients/python/hid_v3.py'),
             'cpp': ('hid_v3.hpp.in', root/'clients/cpp/hid_v3.hpp'),
             'rust': ('hid_v3.rs.in', root/'clients/rust/hid_v3.rs')}
generated = {}
for language, (source, _) in templates.items():
    text = (root/'scripts/clients'/source).read_text(encoding='utf-8')
    text = text.replace('@HEADER@', headers[language]).replace('@OPCODES@', blocks[language].rstrip('\n'))
    generated[language] = text

outputs={root/'firmware/engine/src/keys_generated.rs':eng, root/'firmware/engine/tests/data/vectors_generated.rs':eng_vectors, shared/'src/keys_generated.rs':rust,shared/'keys_generated.js':js}
outputs.update({path: generated[language] for language, (_, path) in templates.items()})
# Firmware sources are hand authored: nothing else is generated per board.
for path,content in outputs.items():
    if a.check:
        if not path.exists() or path.read_text(encoding='utf-8')!=content:raise SystemExit('Stale generated file: '+str(path))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
if a.peer:
    # EvanRemote no longer vendors the protocol crate: it consumes the canonical
    # `shared/input-protocol` through the GDBOX SDK's path dependencies, so there
    # is nothing to copy — only the reference itself is checked.
    vendored=a.peer/'crates/input-protocol'
    if vendored.exists():raise SystemExit('Peer still vendors crates/input-protocol: '+str(vendored))
    for crate in ('evan-core','evan-hardware-input'):
        manifest=a.peer/'crates'/crate/'Cargo.toml'
        if not manifest.exists() or 'shared/input-protocol' not in manifest.read_text():
            raise SystemExit('Peer does not use the canonical input-protocol: '+str(manifest))
    hardware=a.peer/'crates/evan-hardware-input/Cargo.toml'
    if 'sdk/rust' not in hardware.read_text():
        raise SystemExit('Peer hardware input does not use the GDBOX SDK: '+str(hardware))
    key_table=a.peer/'web/key-usages.js'
    if a.check:
        if key_table.read_text()!=js:raise SystemExit('Browser key table drift')
    else:
        key_table.write_text(js)

if a.mscv_rust:
    target=a.mscv_rust/'crates/input-protocol'
    if a.check:
        for path in shared.rglob('*'):
            if path.is_file() and 'target' not in path.relative_to(shared).parts and path.name != 'Cargo.lock':
                other=target/path.relative_to(shared)
                if not other.exists() or other.read_bytes()!=path.read_bytes():raise SystemExit('MSCV Rust drift: '+str(other))
    else:
        shutil.copytree(shared,target,dirs_exist_ok=True,ignore=shutil.ignore_patterns('target','Cargo.lock'))
if a.mscv_cpp:
    tokens='// Generated from FirmwareManageTool_Rust/shared/input-protocol/keys.json.\n#pragma once\n#include <cstdint>\nnamespace hardware::v3 {\nstruct KeyToken { const char* token; std::uint16_t page, usage; };\ninline constexpr KeyToken KeyTokens[] = {\n'
    tokens+=''.join('    {'+json.dumps(token)+', '+str(row['page'])+', '+str(row['usage'])+'},\n' for row in rows for token in [row['token']]+row['aliases'])
    tokens+='};\n}\n'
    for path,content in {a.mscv_cpp/'include/hardware/input_protocol/key_tokens_generated.h':tokens,a.mscv_cpp/'include/hardware/input_protocol/vectors_generated.h':cpp_vectors.replace('#pragma once', '#pragma once\n#include <stdint.h>')}.items():
        if a.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit('MSCV C++ drift: '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
