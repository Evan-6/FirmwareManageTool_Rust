#!/usr/bin/env python3
"""Generate the Rust firmware's USB report descriptors from the C++ sketch.

The C++ arrays stay the source of truth until the C++ firmware is removed, so the
Rust PoC cannot drift: this script parses both the shipping sketch and the frozen
golden header, refuses to emit anything when they disagree, and can `--check` the
committed Rust file.
"""
from pathlib import Path
import argparse, re, subprocess, sys

root = Path(__file__).resolve().parents[1]
sketch = root / 'firmware/boards/rp2040/src/platform/UsbDescriptors.cpp'
constants = root / 'firmware/boards/rp2040/src/input/WireCodec.h'
golden = root / 'firmware/tests/Rp2040UsbGolden.h'
target = root / 'firmware/app/src/usb_descriptors.rs'

ARRAY = re.compile(r'(?:const|constexpr)\s+(?:uint8_t|u8)\s+(\w+)\s*\[\]\s*=\s*\{(.*?)\};', re.S)
CONST = re.compile(r'constexpr\s+uint8_t\s+([^;]+);')


def named_constants(text):
    """Report ids appear as identifiers in the descriptor arrays."""
    values = {}
    for declaration in CONST.findall(text):
        for part in declaration.split(','):
            name, _, value = part.partition('=')
            name, value = name.strip(), value.strip()
            if name and value.isdigit():
                values[name] = int(value)
    return values


def arrays(text, names=None):
    names = names or {}
    found = {}
    for name, body in ARRAY.findall(text):
        body = re.sub(r'//[^\n]*', '', body)
        body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
        values = []
        for token in re.findall(r'0x[0-9a-fA-F]+|\d+|[A-Za-z_]\w*', body):
            if token in names:
                values.append(names[token])
            elif token.isdigit() or token.lower().startswith('0x'):
                values.append(int(token, 0))
            else:
                raise SystemExit(f'{name}: unknown identifier {token!r}')
        found[name] = values
    return found


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    names = named_constants(constants.read_text(encoding='utf-8'))
    sketch_arrays = arrays(sketch.read_text(encoding='utf-8'), names)
    golden_arrays = arrays(golden.read_text(encoding='utf-8'))
    pairs = [
        ('INPUT_REPORT_DESCRIPTOR', 'HidReportDescriptor', 'InputDescriptor'),
        ('VENDOR_REPORT_DESCRIPTOR', 'VendorHidReportDescriptor', 'VendorDescriptor'),
    ]
    lines = [
        '// Generated by scripts/gen-usb-descriptors.py from',
        '// firmware/boards/rp2040/src/platform/UsbDescriptors.cpp; do not edit.',
        '',
    ]
    for rust_name, cpp_name, golden_name in pairs:
        current = sketch_arrays[cpp_name]
        frozen = golden_arrays[golden_name]
        if current != frozen:
            raise SystemExit(f'{cpp_name} no longer matches the frozen golden {golden_name}')
        if not current:
            raise SystemExit(f'{cpp_name} is empty or unparsable')
        lines.append(f'/// `{cpp_name}` as compiled by the shipping sketch ({len(current)} bytes).')
        lines.append(f'pub const {rust_name}: &[u8] = &[')
        for i in range(0, len(current), 12):
            lines.append('    ' + ', '.join(f'0x{b:02x}' for b in current[i:i + 12]) + ',')
        lines.append('];')
        lines.append('')

    text = '\n'.join(lines)
    formatted = subprocess.run(['rustfmt', '--edition', '2021'], input=text, text=True,
                               capture_output=True)
    if formatted.returncode == 0:
        text = formatted.stdout

    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != text:
            raise SystemExit(f'Stale generated file: {target}')
        print('USB descriptors match the C++ sketch and the frozen golden')
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding='utf-8')
    print(f'wrote {target.relative_to(root)}')


if __name__ == '__main__':
    main()
